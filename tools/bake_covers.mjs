#!/usr/bin/env node
// Bakes the static layers of every case cover into two transparent WebP images
// (apps/web/public/cases/baked/<slug>-back.webp and <slug>-front.webp) and writes
// apps/web/src/components/bakedCovers.ts (slug → cover signature). CaseArt then renders
// <img back> + live skin/fx/LED + <img front> instead of ~250 SVG nodes per cover.
//
// Needs the web dev server (renders /dev/cover/[slug], which 404s in production) and the API.
// Idempotent: a cover is re-baked only when its signature (case data + art presence + ART_REV in
// CaseArt.tsx) changed or a file is missing. Run again whenever art/cases change:
// The manifest is written once at the end (writing it mid-run would hot-reload the dev page).
//   node tools/bake_covers.mjs [--web http://localhost:3000] [--api http://localhost:4000] [--force] [--only a,b]
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'apps/web/public/cases/baked');
const MANIFEST = path.join(ROOT, 'apps/web/src/components/bakedCovers.ts');
const CHROME = process.env.CHROME ?? `${process.env.HOME}/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome`;
const BLEED = 0.12; // must match BAKE_BLEED in CaseArt.tsx
const PORT = 9479;

const args = process.argv.slice(2);
const opt = (name, def) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : def;
};
const WEB = opt('web', 'http://localhost:3000');
const API = opt('api', 'http://localhost:4000');
const FORCE = args.includes('--force');
const ONLY = opt('only', '')
  .split(',')
  .filter(Boolean);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function readManifest() {
  if (!existsSync(MANIFEST)) return {};
  const m = readFileSync(MANIFEST, 'utf8').match(/=\s*(\{[\s\S]*\});/);
  try {
    return m ? JSON.parse(m[1]) : {};
  } catch {
    return {};
  }
}
function writeManifest(map) {
  const sorted = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(
    MANIFEST,
    '// Generated by tools/bake_covers.mjs — slug → signature of the baked static cover layers.\n' +
      `export const BAKED: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`,
  );
}

const cases = (await (await fetch(`${API}/cases`)).json()).filter((c) => !c.imageUrl && (!ONLY.length || ONLY.includes(c.slug)));
if (!cases.length) {
  console.log('nothing to bake');
  process.exit(0);
}
mkdirSync(OUT_DIR, { recursive: true });
const manifest = readManifest();

const prof = mkdtempSync(path.join(tmpdir(), 'bake-'));
const chrome = spawn(CHROME, ['--headless=new', '--no-sandbox', '--hide-scrollbars', `--remote-debugging-port=${PORT}`, `--user-data-dir=${prof}`, '--window-size=900,800', 'about:blank'], { stdio: 'ignore' });
let target;
for (let i = 0; i < 100 && !target; i++) {
  try {
    target = (await (await fetch(`http://127.0.0.1:${PORT}/json`)).json()).find((t) => t.type === 'page');
  } catch {}
  if (!target) await sleep(200);
}
const ws = new WebSocket(target.webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let seq = 0;
const pend = new Map();
ws.onmessage = (m) => {
  const d = JSON.parse(m.data);
  if (d.id && pend.has(d.id)) {
    pend.get(d.id)(d);
    pend.delete(d.id);
  }
};
const send = (method, params = {}) =>
  new Promise((r) => {
    const i = ++seq;
    pend.set(i, r);
    ws.send(JSON.stringify({ id: i, method, params }));
  });
const ev = async (expression) => {
  const r = await send('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true });
  if (r.result?.exceptionDetails) throw new Error(JSON.stringify(r.result.exceptionDetails).slice(0, 400));
  return r.result?.result?.value;
};

try {
  await send('Emulation.setDeviceMetricsOverride', { width: 900, height: 800, deviceScaleFactor: 2, mobile: false });
  await send('Emulation.setDefaultBackgroundColorOverride', { color: { r: 0, g: 0, b: 0, a: 0 } });
  await send('Page.enable');
  await send('Page.navigate', { url: `${WEB}/dev/cover/${cases[0].slug}` });
  for (let i = 0; i < 150 && !(await ev('typeof window.__bake === "function"')); i++) await sleep(200);
  if (!(await ev('typeof window.__bake === "function"'))) throw new Error('bake page did not load (is the dev server running?)');
  await ev(`(() => { const s = document.createElement('style'); s.textContent = ${JSON.stringify(`
    html, body { background: transparent !important; }
    body::before, body::after { display: none !important; }
    body * { visibility: hidden !important; }
    #bake-target, #bake-target * { visibility: visible !important; }
    *, *::before, *::after { animation: none !important; transition: none !important; }
    #bake-target .cart-skin-wrap, #bake-target .cart-fx, #bake-target .cart-led { display: none !important; }
    html.bake-back #bake-target .cart-front { display: none !important; }
    html.bake-front #bake-target .cart-back > :not(defs), html.bake-front #bake-target .cart-bgimg { display: none !important; }
    /* (keep the back <svg> itself rendered: the front layer references its gradient <defs>) */
  `)}; document.head.appendChild(s); return 1; })()`);

  let baked = 0;
  let skipped = 0;
  for (const c of cases) {
    const sig = await ev(`window.__bake(${JSON.stringify(c.slug)})`);
    if (!sig) {
      console.warn(`! ${c.slug}: not rendered`);
      continue;
    }
    const files = ['back', 'front'].map((l) => path.join(OUT_DIR, `${c.slug}-${l}.webp`));
    if (!FORCE && manifest[c.slug] === sig && files.every((f) => existsSync(f))) {
      skipped++;
      continue;
    }
    const r = await ev(`(() => { const b = document.querySelector('#bake-target .cart-stage').getBoundingClientRect(); return [b.x, b.y, b.width, b.height]; })()`);
    const clip = { x: r[0] - r[2] * BLEED, y: r[1] - r[3] * BLEED, width: r[2] * (1 + 2 * BLEED), height: r[3] * (1 + 2 * BLEED), scale: 1 };
    for (const [i, layer] of ['back', 'front'].entries()) {
      await ev(`document.documentElement.className = 'bake-${layer}'; new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)))`);
      const shot = await send('Page.captureScreenshot', { format: 'webp', quality: 82, clip, captureBeyondViewport: false });
      writeFileSync(files[i], Buffer.from(shot.result.data, 'base64'));
    }
    manifest[c.slug] = sig;
    baked++;
    process.stdout.write(`baked ${c.slug}\n`);
  }
  writeManifest(manifest);
  console.log(`done: ${baked} baked, ${skipped} up to date, ${Object.keys(manifest).length} in manifest`);
} finally {
  ws.close();
  chrome.kill();
  await sleep(300);
  rmSync(prof, { recursive: true, force: true });
}
