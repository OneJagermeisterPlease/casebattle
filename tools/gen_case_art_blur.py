"""Tiny pre-blurred backdrop thumbnails for case covers (perf: no runtime CSS blur/filter/mask).

For every painting in apps/web/public/cases/{art,scenes}/*.webp writes a 48x48 WebP to
apps/web/public/cases/{art-blur,scenes-blur}/<name>.webp that is already blurred, darkened,
saturated and radially faded to transparent (alpha vignette), then rewrites
apps/web/src/components/caseArtBlur.ts with the set of slugs that have an art thumb.

Run any time new art arrives (idempotent, ~1 s for a few hundred files):
    ~/.cache/cc-imagegen/venv/bin/python tools/gen_case_art_blur.py
"""

from __future__ import annotations

import math
from pathlib import Path

from PIL import Image, ImageEnhance, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
PUB = ROOT / "apps/web/public/cases"
TS_OUT = ROOT / "apps/web/src/components/caseArtBlur.ts"
SIZE = 48


def vignette(size: int) -> Image.Image:
    """Alpha mask: opaque up to 45% of the radius, smooth fade to 0 at the edge (closest-side)."""
    m = Image.new("L", (size, size))
    c = (size - 1) / 2
    px = m.load()
    for y in range(size):
        for x in range(size):
            r = math.hypot(x - c, y - c) / (size / 2)
            t = 0.0 if r <= 0.45 else min(1.0, (r - 0.45) / 0.55)
            a = 1.0 - t * t * (3 - 2 * t)  # smoothstep
            px[x, y] = int(255 * a)
    return m


def thumb(src: Path, dst: Path, mask: Image.Image) -> None:
    im = Image.open(src).convert("RGB").resize((SIZE, SIZE), Image.LANCZOS)
    im = im.filter(ImageFilter.GaussianBlur(2.2))
    im = ImageEnhance.Color(im).enhance(1.4)
    im = ImageEnhance.Brightness(im).enhance(0.6)
    im = im.convert("RGBA")
    im.putalpha(mask)
    dst.parent.mkdir(parents=True, exist_ok=True)
    im.save(dst, "WEBP", quality=82, method=6)


def main() -> None:
    mask = vignette(SIZE)
    slugs: list[str] = []
    for kind in ("art", "scenes"):
        src_dir = PUB / kind
        if not src_dir.is_dir():
            continue
        for src in sorted(src_dir.glob("*.webp")):
            dst = PUB / f"{kind}-blur" / src.name
            if not dst.exists() or dst.stat().st_mtime < src.stat().st_mtime:
                thumb(src, dst, mask)
            if kind == "art":
                slugs.append(src.stem)
    body = ", ".join(f'"{s}"' for s in slugs)
    TS_OUT.write_text(
        "// Generated by tools/gen_case_art_blur.py — slugs that have /cases/art-blur/<slug>.webp.\n"
        f"export const CASE_ART_BLUR = new Set<string>([{body}]);\n",
        encoding="utf-8",
    )
    print(f"{len(slugs)} art thumbs, scenes in {PUB / 'scenes-blur'}")


if __name__ == "__main__":
    main()
